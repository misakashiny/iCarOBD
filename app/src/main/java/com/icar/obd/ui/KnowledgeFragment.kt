            Section(
                "5. 怎么分析 CAN（被动）—— 采样率是前提",
                """
                PID 页 → CAN 探测。或 CAN 探测页开常驻监听。

                ⚠️ 第一条铁律：采样率是前提，不是细节。
                判断"能不能看见一个信号"之前，先算：

                适配器实际帧率 ÷ 目标 ID 的广播频率 = 你每秒能采到几帧

                本项目实车实测：
                · 不过滤：总共只漏出约 77 帧/秒，摊到 80 个 ID 上 → 每个 ID 每秒 1 帧
                　 结果：0x09A 20 秒只采到 4~5 帧，1.4 Hz 的转向灯闪烁被完全抹平
                　 （changed 一直是 0，看起来像"这个 ID 不动"）
                · 单 ID 过滤（ATCRA09A）：0x09A 从 0.7 帧/秒 → 20 帧/秒
                · 段过滤（ATCM700+ATCF000）：总帧数 77/秒 → 344 帧/秒

                所以：想看清一个信号，就把它单独放行。

                过滤器三档（本项目按监听信号自动选）：
                · 只有一个 ID → ATCRA<id>（最省）
                · 多个 ID 落在同一 0x100 段 → ATCM700 + ATCF<段>
                · 跨多个段 → 不加过滤器（会打一条警告）—— 这是最坏情况，注意 ANR 风险

                ⚠️ 段号看 ATCF 的高三位：ATCF000 在掩码 ATCM700 下才是"0x0xx 段"；
                单独发 ATCF000 是整条总线（不是第 0 段）。掩码与过滤是一对，缺一不可。
                """.trimIndent()
            ),

