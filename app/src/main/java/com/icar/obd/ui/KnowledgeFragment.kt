        val SECTIONS: List<Section> = listOf(

            // ============================================================ 知识 0~18

            Section(
                "0. 先看这个：数据从哪来（三条链路）",
                """
                ① 主动请求（轮询）—— 发 01 0C 这样的请求，ECU 应答。
                　 标准 PID、厂家 Mode 22 都走这条。受轮询节奏限制，一条一条排队。
                ② 广播帧（监听）—— 别的模块自己在总线上周期性喊，你只能听。
