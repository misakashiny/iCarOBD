'use strict';
// Original geometry, no dependencies, never writes over legacy assets.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const {Canvas}=require('../png.js');
const catalog=require('./catalog.json');
const root=path.resolve(__dirname,'..');
const output=process.argv[2]?path.resolve(process.argv[2]):root;
const dir=path.join(output,'assets/next/v1');fs.mkdirSync(dir,{recursive:true});
const assets=[];
for(const style of catalog.styles){
  const c=new Canvas(256,256,4);
  c.roundRect(4,4,248,248,style.radius,style.edge);
  c.roundRect(5.5,5.5,245,245,Math.max(0,style.radius-1.5),style.background);
  if(style.id==='sport')for(let x=16;x<240;x+=16)c.line(x,240,x+6,234,1,'#263A4C');
  if(style.id==='oem')c.line(24,228,232,228,1,'#2B3F50');
  const file=style.id+'-panel.png',png=c.toPng();fs.writeFileSync(path.join(dir,file),png);
  assets.push({name:style.id+'-panel',label:style.name+'新仪表底板',kind:'frame',path:'assets/next/v1/'+file,w:256,h:256,data:'data:image/png;base64,'+png.toString('base64'),sha256:crypto.createHash('sha256').update(png).digest('hex')});
}
const manifest={...catalog,assets};
fs.mkdirSync(path.join(output,'next-library'),{recursive:true});
fs.writeFileSync(path.join(output,'next-library/manifest.json'),JSON.stringify(manifest,null,2)+'\n');
fs.writeFileSync(path.join(output,'next-library/data.js'),'/* Generated by next-library/generate.js; classic script for file://. */\nwindow.NEXT_LIBRARY = '+JSON.stringify(manifest)+';\n');
console.log('Generated 5 semantic controls / 15 variants / 3 original transparent PNG panels in '+output);
